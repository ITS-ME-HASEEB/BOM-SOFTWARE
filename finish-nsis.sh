#!/usr/bin/env bash
# finish-nsis.sh — complete the NSIS installer build without wine:
#   1. stamp the app exe with icon + version (pure JS, Electron exe — safe)
#   2. rebuild the 7z payload with the stamped exe
#   3. extract the uninstaller from the stub (pure JS)
#   4. second makensis pass -> final installer
#   5. validate the final installer's embedded uninstaller byte-for-byte
#
# IMPORTANT: the installer and uninstaller are NSIS executables. They must NOT
# be modified after makensis writes them — rewriting them breaks NSIS's
# integrity check and causes "NSIS Error". Their icon + version info are
# embedded by makensis itself via -DMUI_ICON / -XVIAddVersionKey.
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(pwd)"

APP_EXE="$ROOT/release/win-unpacked/Maaz Dawakhana.exe"
STUB="$ROOT/release/Maaz-Dawakhana-Setup-1.0.7.exe"
UNINST="$ROOT/release/__uninstaller-nsis-maaz-dawakhana-desktop.exe"
ARCHIVE="$ROOT/release/maaz-dawakhana-desktop-1.0.7-x64.nsis.7z"
OUT="$ROOT/release/Maaz-Dawakhana-Setup-1.0.7.exe"
MAKENSIS="$HOME/.cache/electron-builder/nsis/nsis-3.0.4.1/linux/makensis"
SEVENZA="$ROOT/node_modules/7zip-bin/linux/x64/7za"
NSIS_TEMPLATES="$ROOT/node_modules/app-builder-lib/templates/nsis"

[ -f "$APP_EXE" ] || { echo "missing $APP_EXE"; exit 1; }
[ -f "$STUB" ] || { echo "missing $STUB"; exit 1; }
[ -x "$MAKENSIS" ] || { echo "missing $MAKENSIS"; exit 1; }

echo "== 1. stamp app exe =="
node stamp-exe.js "$APP_EXE" build/icon.ico

echo "== 2. rebuild 7z payload =="
rm -f "$ARCHIVE"
( cd release/win-unpacked && "$SEVENZA" a -bd -mx=9 -md=1m -mtc=off -ms=off -mtm=off -mta=off "$ARCHIVE" . -xr!*.avi -xr!*.mov -xr!*.m4v -xr!*.mp4 -xr!*.m4p -xr!*.qt -xr!*.mkv -xr!*.webm -xr!*.vmdk ) >/dev/null

HASH=$(sha512sum "$ARCHIVE" | cut -d' ' -f1 | tr 'a-f' 'A-F')
SIZE_KB=$(( $(du -sk release/win-unpacked | cut -f1) ))
echo "archive hash: ${HASH:0:16}…  unpacked KB: $SIZE_KB"

echo "== 3. extract uninstaller from stub =="
rm -f "$UNINST"
node -e "
const { UninstallerReader } = require('app-builder-lib/out/targets/nsis/nsisUtil');
UninstallerReader.exec('$STUB', '$UNINST').then(() => console.log('uninstaller extracted:', require('fs').statSync('$UNINST').size, 'bytes')).catch(e => { console.error(e); process.exit(1); });
"

echo "== 4. second makensis pass =="
# The exact installer script generated by electron-builder (logged with DEBUG=electron-builder):
[ -f "$ROOT/release/nsis-script.nsi" ] || { echo "missing release/nsis-script.nsi — run build-installer.sh"; exit 1; }
cd "$NSIS_TEMPLATES"
export NSISDIR="$HOME/.cache/electron-builder/nsis/nsis-3.0.4.1"
LC_ALL=C.UTF-8 "$MAKENSIS" -WX -INPUTCHARSET UTF8 \
  -DAPP_ID=com.maazdawakhana.desktop \
  -DAPP_GUID=cc9966fa-80d1-5f13-9449-b707098f876a \
  -DUNINSTALL_APP_KEY=cc9966fa-80d1-5f13-9449-b707098f876a \
  -DPRODUCT_NAME=Maaz\ Dawakhana \
  -DPRODUCT_FILENAME=Maaz\ Dawakhana \
  -DAPP_FILENAME=Maaz\ Dawakhana \
  "-DAPP_DESCRIPTION=Maaz Dawakhana — BOM & Production Control for Windows. Local data, no login." \
  -DVERSION=1.0.7 \
  "-DPROJECT_DIR=$ROOT" \
  "-DBUILD_RESOURCES_DIR=$ROOT/build" \
  -DAPP_PACKAGE_NAME=maaz-dawakhana-desktop \
  "-DMUI_ICON=$ROOT/build/icon.ico" \
  "-DMUI_UNICON=$ROOT/build/icon.ico" \
  "-DAPP_64=$ARCHIVE" \
  -DAPP_64_NAME=maaz-dawakhana-desktop-1.0.7-x64.nsis.7z \
  -DAPP_64_HASH="$HASH" \
  -DAPP_64_UNPACKED_SIZE="$SIZE_KB" \
  -DCOMPANY_NAME=Maaz\ Dawakhana \
  '-DAPP_INSTALLER_STORE_FILE=maaz-dawakhana-desktop-updater\installer.exe' \
  -DCOMPRESSION_METHOD=7z \
  -DMULTIUSER_INSTALLMODE_ALLOW_ELEVATION \
  -DINSTALL_MODE_PER_ALL_USERS_REQUIRED \
  -DallowToChangeInstallationDirectory \
  -DSHORTCUT_NAME=Maaz\ Dawakhana \
  -DUNINSTALL_DISPLAY_NAME=Maaz\ Dawakhana\ 1.0.7 \
  '-DMUI_WELCOMEFINISHPAGE_BITMAP=${NSISDIR}\Contrib\Graphics\Wizard\nsis3-metro.bmp' \
  '-DMUI_UNWELCOMEFINISHPAGE_BITMAP=${NSISDIR}\Contrib\Graphics\Wizard\nsis3-metro.bmp' \
  -DESTIMATED_SIZE="$SIZE_KB" \
  -DCOMPRESS=auto \
  "-DUNINSTALLER_OUT_FILE=$UNINST" \
  "-XOutFile $OUT" \
  '-XVIProductVersion 1.0.7.0' \
  '-XVIAddVersionKey /LANG=1033 ProductName "Maaz Dawakhana"' \
  '-XVIAddVersionKey /LANG=1033 ProductVersion "1.0.7"' \
  '-XVIAddVersionKey /LANG=1033 LegalCopyright "Copyright © 2026 Maaz Dawakhana"' \
  '-XVIAddVersionKey /LANG=1033 FileDescription "Maaz Dawakhana — BOM & Production Control for Windows. Local data, no login."' \
  '-XVIAddVersionKey /LANG=1033 FileVersion "1.0.7"' \
  '-XVIAddVersionKey /LANG=1033 CompanyName "Maaz Dawakhana"' \
  '-XUnicode true' \
  '-XSetCompressor zlib' \
  - < "$ROOT/release/nsis-script.nsi"
cd "$ROOT"

echo "== 5. sanity checks =="
node -e "
const fs = require('fs');
const crypto = require('crypto');
const buf = fs.readFileSync('$OUT');
if (buf[0] !== 0x4d || buf[1] !== 0x5a) { console.error('FAIL: not a PE executable'); process.exit(1); }
if (buf.length < 50 * 1024 * 1024) { console.error('FAIL: installer too small — payload missing'); process.exit(1); }
const uninst = fs.readFileSync('$UNINST');
if (uninst[0] !== 0x4d || uninst[1] !== 0x5a || uninst.length < 100 * 1024) { console.error('FAIL: uninstaller invalid'); process.exit(1); }
console.log('installer:', (buf.length / 1048576).toFixed(1) + ' MB', '| MZ OK');
console.log('uninstaller:', (uninst.length / 1024).toFixed(0) + ' KB', '| MZ OK');
console.log('installer sha256:', crypto.createHash('sha256').update(buf).digest('hex'));
console.log('NOTE: makensis embedded the CRC at compile time; no post-processing touches this file.');
"

echo
ls -la release/Maaz-Dawakhana-Setup-1.0.7.exe
echo "DONE — installer is untouched by post-processing, NSIS data intact."
